// Builds skills/apple-ui/tokens/apple-glass-controls.js (+ .global.js) from apple-glass-controls.json and
// apple-glass-controls.src.js. Edit the JSON (numbers) or the .src.js (code), then run: node tools/build-glass-controls.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "skills", "apple-ui", "tokens");
const data = JSON.stringify(JSON.parse(readFileSync(join(dir, "apple-glass-controls.json"), "utf8")));
let src = readFileSync(join(dir, "apple-glass-controls.src.js"), "utf8");
src = src.replace(/\/\*DATA\*\/[\s\S]*?\/\*END\*\//, () => data);
src = src.replace(/^\/\/ SOURCE of[\s\S]*?\n\/\/\n/, "// GENERATED by tools/build-glass-controls.mjs from apple-glass-controls.json + apple-glass-controls.src.js - do not edit by hand.\n//\n");
writeFileSync(join(dir, "apple-glass-controls.js"), src);
const g = src.replace(/^export default .*$/m, "").replace(/^export (class|function|const) /gm, "$1 ");
writeFileSync(join(dir, "apple-glass-controls.global.js"), "(function(){\n" + g + "\nwindow.GlassControls = GlassControls;\n})();\n");
console.log("built tokens/apple-glass-controls.js and .global.js");
